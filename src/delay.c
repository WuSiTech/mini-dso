/* cpv - 可标定的微秒延时: DELAY_US_ITER 次空循环约 1us (45MHz 1T, 待实测标定)
   参数 us 为整数微秒, 内部按 1000us 分段避免 16 位溢出 */
#define DELAY_US_ITER 4
void DelayUs(uint16 us)
{
    uint16 n;

    while (us)
    {
        if (us > 1000)
        {
            n = 1000 * DELAY_US_ITER;
            us -= 1000;
        }
        else
        {
            n = us * DELAY_US_ITER;
            us = 0;
        }
        while (n)
            n--;
    }
}
